import AppKit
import Observation

struct Entrada: Codable, Identifiable, Hashable, Sendable {
    enum Tipo: String, Codable, Sendable { case ditado, clipboard }

    var id = UUID()
    var data = Date()
    let tipo: Tipo
    let texto: String
    var bruto: String?  // transcrição antes da correção (só ditado)
    var app: String?
}

/// Catálogo de ditados e do que passou pelo clipboard, salvo em JSON em Application Support.
@MainActor @Observable
final class Historico {
    private(set) var entradas: [Entrada] = []
    private let limite = 1000  // ponytail: JSON inteiro reescrito a cada entrada; SQLite se passar de alguns milhares
    private let arquivo: URL
    private var ultimoChangeCount = NSPasteboard.general.changeCount
    private var monitor: Timer?

    init() {
        let pasta = URL.applicationSupportDirectory.appending(path: "Kanji")
        try? FileManager.default.createDirectory(at: pasta, withIntermediateDirectories: true)
        arquivo = pasta.appending(path: "historico.json")
        if let dados = try? Data(contentsOf: arquivo) {
            let lidas = (try? JSONDecoder().decode([Entrada].self, from: dados)) ?? []
            // Apaga segredos que entraram antes deste filtro existir.
            entradas = lidas.filter { !($0.tipo == .clipboard && Self.pareceSegredo($0.texto)) }
            if entradas.count != lidas.count { salvar() }
        }
    }

    /// Chave de API, token ou URL com senha em qualquer parte do texto ("export KEY=…", "Bearer …", um .env).
    /// Sites como o Console da Anthropic não marcam o clipboard como Concealed, então o tipo não basta
    /// (uma chave foi parar no histórico assim).
    // ponytail: heurística; hash e UUID longos também ficam de fora, o que é aceitável para um histórico
    static func pareceSegredo(_ texto: String) -> Bool {
        texto.split(whereSeparator: \.isWhitespace).contains { palavra in
            guard let esquema = palavra.range(of: "://") else {
                let valor = palavra.split(separator: "=", maxSplits: 1).last ?? palavra  // KEY=valor
                return valor.count >= 32 && valor.contains(where: \.isNumber) && valor.contains(where: \.isLetter)
            }
            return palavra[esquema.upperBound...].split(separator: "/").first?.contains("@") == true  // usuario:senha@host
        }
    }

    func adicionar(_ entrada: Entrada) {
        guard entrada.texto != entradas.first?.texto else { return }
        entradas = Array(([entrada] + entradas).prefix(limite))
        salvar()
    }

    func remover(_ ids: Set<Entrada.ID>) {
        entradas = entradas.filter { !ids.contains($0.id) }
        salvar()
    }

    func limpar() {
        entradas = []
        salvar()
    }

    private func salvar() {
        do {
            try JSONEncoder().encode(entradas).write(to: arquivo, options: .atomic)
        } catch {
            NSLog("Kanji: falha ao salvar histórico: \(error)")
        }
    }

    // MARK: - Monitor do clipboard

    /// O macOS não avisa mudanças no clipboard; todo gerenciador de clipboard faz polling do changeCount.
    func monitorar(_ ligado: Bool) {
        monitor?.invalidate()
        monitor = nil
        guard ligado else { return }
        ultimoChangeCount = NSPasteboard.general.changeCount
        monitor = .scheduledTimer(withTimeInterval: 0.5, repeats: true) { _ in
            MainActor.assumeIsolated { self.verificarClipboard() }
        }
    }

    /// Chamado quando o próprio Kanji escreve no clipboard, para não duplicar o ditado.
    func ignorarMudancaAtual() {
        ultimoChangeCount = NSPasteboard.general.changeCount
    }

    // Convenção nspasteboard.org: gerenciadores de senha marcam o conteúdo como Concealed/Transient.
    private static let tiposSensiveis: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
    ]

    private func verificarClipboard() {
        let pb = NSPasteboard.general
        guard pb.changeCount != ultimoChangeCount else { return }
        ultimoChangeCount = pb.changeCount
        let tipos = Set(pb.types?.map(\.rawValue) ?? [])
        guard tipos.isDisjoint(with: Self.tiposSensiveis),
              let texto = pb.string(forType: .string),
              !texto.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty, !Self.pareceSegredo(texto)
        else { return }
        adicionar(.init(tipo: .clipboard, texto: texto, app: NSWorkspace.shared.frontmostApplication?.localizedName))
    }
}
